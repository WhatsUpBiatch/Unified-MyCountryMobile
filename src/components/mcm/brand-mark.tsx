/* Some brands are black or near enough — GitHub, Notion, Zendesk — and on a
   dark surface they disappear. Those switch to a token that follows the theme
   instead of their own hex; every other brand keeps its colour, which is the
   part people recognise. The threshold is perceived brightness, so a dark
   green counts as dark and a mid-blue does not. */
const ink = (hex: string) => {
  const n = parseInt(hex.slice(1), 16);
  const r = (n >> 16) & 255;
  const g = (n >> 8) & 255;
  const b = n & 255;
  const brightness = (r * 299 + g * 587 + b * 114) / 1000;
  return brightness < 70 ? 'var(--brand-ink, #181717)' : hex;
};

/* Matched on the slug the API sends, then on the display name, so a toolkit
   that arrives as "GitHub" or "github" or "Github" resolves the same way. */
const key = (slug: string, name?: string) =>
  String(slug || name || '')
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '');

export const hasBrandMark = (slug: string, name?: string) => {
  const k = key(slug, name);
  return k === 'slack' || k in MARKS;
};

export const BrandMark = ({
  slug,
  name,
  size = 18,
}: {
  slug: string;
  name?: string;
  size?: number;
}) => {
  const k = key(slug, name);

  if (k === 'slack') {
    return (
      <svg width={size} height={size} viewBox="0 0 24 24" role="img" aria-label="Slack">
        {SLACK.map((part) => (
          <path key={part.hex} d={part.d} fill={part.hex} />
        ))}
      </svg>
    );
  }

  const mark = MARKS[k];
  if (!mark) return null;
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={ink(mark.hex)}
      role="img"
      aria-label={mark.title}
    >
      <path d={mark.path} />
    </svg>
  );
};

export default BrandMark;
